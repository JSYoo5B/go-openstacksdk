// ServerBlockDevice is one explicit block_device_mapping_v2 entry with every
// per-mapping field Nova accepts at creation. UUID is sent literally. Zero
// strings, zero VolumeSize, false NoDevice and nil DeleteOnTermination omit
// their keys; BootIndex distinguishes omitted, an integer and null.
// Tag requires Compute 2.42 and VolumeType 2.67.
type ServerBlockDevice struct {
	SourceType          string
	DestinationType     string
	UUID                string
	BootIndex           request.Optional[int]
	DeleteOnTermination *bool
	DeviceName          string
	DeviceType          string
	DiskBus             string
	GuestFormat         string
	VolumeSize          int
	VolumeType          string
	Tag                 string
	NoDevice            bool
}

// LegacyBlockDevice is one legacy block_device_mapping (v1) entry. DeviceName
// is required. Legacy mappings cannot be combined with any v2 mapping.
type LegacyBlockDevice struct {
	DeviceName          string
	VolumeID            string
	SnapshotID          string
	VolumeSize          int
	DeleteOnTermination *bool
	NoDevice            bool
}

// WithBlockDeviceMappings sends explicit block_device_mapping_v2 entries.
// Like Python's cloud create_server, mappings generated by WithBootVolume,
// WithBootVolumeSize and WithDataVolumes are appended after them. A later
// call replaces earlier explicit mappings.
func WithBlockDeviceMappings(mappings ...ServerBlockDevice) CreateServerOption {
	copied := cloneBlockDevices(mappings)
	return func(o *createServerOptions) error {
		if len(copied) == 0 {
			return invalid("block device mappings must not be empty")
		}
		for i, mapping := range copied {
			if err := mapping.validate(); err != nil {
				return fmt.Errorf("block device mapping %d: %w", i, err)
			}
		}
		o.extra.mappings = cloneBlockDevices(copied)
		return nil
	}
}

// WithLegacyBlockDeviceMappings sends legacy block_device_mapping entries.
func WithLegacyBlockDeviceMappings(mappings ...LegacyBlockDevice) CreateServerOption {
	copied := cloneLegacyBlockDevices(mappings)
	return func(o *createServerOptions) error {
		if len(copied) == 0 {
			return invalid("legacy block device mappings must not be empty")
		}
		for i, mapping := range copied {
			if strings.TrimSpace(mapping.DeviceName) == "" {
				return invalid("legacy block device mapping %d requires a device name", i)
			}
			if mapping.VolumeSize < 0 {
				return invalid("legacy block device mapping %d volume size must not be negative", i)
			}
		}
		o.extra.legacy = cloneLegacyBlockDevices(copied)
		return nil
	}
}

// WithTrustedImageCertificates sends trusted_image_certificates in the given
// order. It requires Compute microversion 2.63 or later; Nova validates the
// certificate IDs and the image signature.
func WithTrustedImageCertificates(ids ...string) CreateServerOption {
	ids = append([]string(nil), ids...)
	return func(o *createServerOptions) error {
		if len(ids) == 0 {
			return invalid("trusted image certificates must not be empty")
		}
		for _, id := range ids {
			if strings.TrimSpace(id) == "" {
				return invalid("trusted image certificate ID must not be empty")
			}
		}
		o.extra.certificates = append([]string(nil), ids...)
		return nil
	}
}

func cloneBlockDevices(mappings []ServerBlockDevice) []ServerBlockDevice {
	out := make([]ServerBlockDevice, len(mappings))
	for i, mapping := range mappings {
		out[i] = mapping
		if mapping.DeleteOnTermination != nil {
			value := *mapping.DeleteOnTermination
			out[i].DeleteOnTermination = &value
		}
	}
	return out
}

func cloneLegacyBlockDevices(mappings []LegacyBlockDevice) []LegacyBlockDevice {
	out := make([]LegacyBlockDevice, len(mappings))
	for i, mapping := range mappings {
		out[i] = mapping
		if mapping.DeleteOnTermination != nil {
			value := *mapping.DeleteOnTermination
			out[i].DeleteOnTermination = &value
		}
	}
	return out
}

func (m ServerBlockDevice) validate() error {
	switch m.SourceType {
	case "image", "volume", "snapshot", "blank":
	default:
		return invalid("source type %q must be image, volume, snapshot or blank", m.SourceType)
	}
	switch m.DestinationType {
	case "", "local", "volume":
	default:
		return invalid("destination type %q must be local or volume", m.DestinationType)
	}
	if m.VolumeSize < 0 {
		return invalid("volume size must not be negative")
	}
	return nil
}

func (m ServerBlockDevice) wire() map[string]any {
	out := map[string]any{"source_type": m.SourceType}
	set := func(key, value string) {
		if value != "" {
			out[key] = value
		}
	}
	set("destination_type", m.DestinationType)
	set("uuid", m.UUID)
	set("device_name", m.DeviceName)
	set("device_type", m.DeviceType)
	set("disk_bus", m.DiskBus)
	set("guest_format", m.GuestFormat)
	set("volume_type", m.VolumeType)
	set("tag", m.Tag)
	if m.BootIndex.IsSet() {
		out["boot_index"] = m.BootIndex
	}
	if m.DeleteOnTermination != nil {
		out["delete_on_termination"] = *m.DeleteOnTermination
	}
	if m.VolumeSize > 0 {
		out["volume_size"] = m.VolumeSize
	}
	if m.NoDevice {
		out["no_device"] = true
	}
	return out
}

func (m LegacyBlockDevice) wire() map[string]any {
	out := map[string]any{"device_name": m.DeviceName}
	if m.VolumeID != "" {
		out["volume_id"] = m.VolumeID
	}
	if m.SnapshotID != "" {
		out["snapshot_id"] = m.SnapshotID
	}
	if m.VolumeSize > 0 {
		out["volume_size"] = m.VolumeSize
	}
	if m.DeleteOnTermination != nil {
		out["delete_on_termination"] = *m.DeleteOnTermination
	}
	if m.NoDevice {
		out["no_device"] = true
	}
	return out
}

func (o *createServerOptions) validateMappings(version string) error {
	for _, mapping := range o.extra.mappings {
		if mapping.Tag != "" && !microversionAtLeast(version, 2, 42) {
			return fmt.Errorf("%w: block device tag requires Compute microversion 2.42 or later (client uses %q)", resource.ErrUnsupported, version)
		}
		if mapping.VolumeType != "" && !microversionAtLeast(version, 2, 67) {
			return fmt.Errorf("%w: block device volume type requires Compute microversion 2.67 or later (client uses %q)", resource.ErrUnsupported, version)
		}
	}
	if len(o.extra.certificates) > 0 && !microversionAtLeast(version, 2, 63) {
		return fmt.Errorf("%w: trusted image certificates require Compute microversion 2.63 or later (client uses %q)", resource.ErrUnsupported, version)
	}
	if len(o.extra.legacy) > 0 && (len(o.extra.mappings) > 0 || len(o.extra.dataVolumes) > 0 || o.bootVolume != nil || o.bootVolumeSize > 0) {
		return invalid("legacy block device mappings cannot be combined with block_device_mapping_v2")
	}
	return nil
}

// ServerReservation is the response to a creation request with
// return_reservation_id. Nova returns only the reservation ID, not a server.
type ServerReservation struct {
	ReservationID string
	resource.Metadata
}

// CreateReservation sends one creation request with return_reservation_id
// true and returns the reservation ID. Combine it with WithServerCount to
// create several servers; list them afterwards with the reservation_id
// server query. WithWait and WithCreateRefresh are rejected because no server
// ID is returned. The POST is never repeated.
func (s *Servers) CreateReservation(ctx context.Context, request CreateServerRequest, opts ...CreateServerOption) (*ServerReservation, error) {
	if ctx == nil {
		return nil, invalid("context is required")
	}
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	o, err := s.prepareCreateServerOptions(request, opts...)
	if err != nil {
		return nil, err
	}
	if o.wait || o.extra.refresh {
		return nil, invalid("reservation creation cannot wait for or refresh a server")
	}
	body, err := s.prepareServerCreateBody(ctx, request, o)
	if err != nil {
		return nil, err
	}
	encoded, err := body.ToServerCreateMap()
	if err != nil {
		return nil, s.wrap("create reservation", err)
	}
	encoded["server"].(map[string]any)["return_reservation_id"] = true
	response, err := rest.DoJSON(ctx, createClient(s.client, body.microversion), http.MethodPost, s.client.ServiceURL("servers"), encoded, nil, 200, 202)
	if err != nil {
		return nil, s.wrap("create reservation", err)
	}
	var reply struct {
		ReservationID *string `json:"reservation_id"`
	}
	if err := json.Unmarshal(response.Body, &reply); err != nil {
		return nil, s.wrap("create reservation", response.Fail(err))
	}
	if reply.ReservationID == nil || *reply.ReservationID == "" {
		return nil, s.wrap("create reservation", response.Fail(errors.New("response has no reservation_id")))
	}
	return &ServerReservation{ReservationID: *reply.ReservationID, Metadata: resource.Metadata{Header: response.Header.Clone(), StatusCode: response.StatusCode}}, nil
}
