package main

import (
	"fmt"
	"go/format"
	"go/types"
	"os"
	"path/filepath"
	"strings"
)

type neutronDeleteSpec struct {
	path     string
	segments []string
}

var neutronDeleteSpecs = []neutronDeleteSpec{
	{"network/v2/networks", []string{"networks"}},
	{"network/v2/subnets", []string{"subnets"}},
	{"network/v2/ports", []string{"ports"}},
	{"network/v2/extensions/layer3/floatingips", []string{"floatingips"}},
	{"network/v2/extensions/layer3/routers", []string{"routers"}},
	{"network/v2/extensions/security/groups", []string{"security-groups"}},
	{"network/v2/extensions/security/rules", []string{"security-group-rules"}},
}

// emitNeutronDelete keeps the native API intact while supplying the audited
// Python proxy's conditional DELETE and missing-safe default as a separate API.
func (g *generator) emitNeutronDelete(pkg *types.Package) error {
	for _, spec := range neutronDeleteSpecs {
		if sdkPath(pkg.Path()) != spec.path {
			continue
		}
		native, ok := pkg.Scope().Lookup("Delete").(*types.Func)
		if !ok {
			return fmt.Errorf("Neutron conditional deletion requires %s.Delete", spec.path)
		}
		sig, ok := native.Type().(*types.Signature)
		if !ok || sig.Variadic() || sig.Params().Len() != 3 || sig.Results().Len() != 1 {
			return fmt.Errorf("Neutron conditional deletion requires native Delete signature: %s", spec.path)
		}
		qualifier := func(p *types.Package) string { return p.Path() }
		for i, wanted := range []string{"context.Context", "*" + upstreamModule + ".ServiceClient", "string"} {
			if types.TypeString(sig.Params().At(i).Type(), qualifier) != wanted {
				return fmt.Errorf("Neutron conditional deletion requires native parameter %d: %s", i, spec.path)
			}
		}
		if types.TypeString(sig.Results().At(0).Type(), qualifier) != pkg.Path()+".DeleteResult" {
			return fmt.Errorf("Neutron conditional deletion requires native DeleteResult: %s", spec.path)
		}
		return g.writeNeutronDelete(spec, pkg.Name())
	}
	return nil
}

func (g *generator) writeNeutronDelete(spec neutronDeleteSpec, name string) error {
	segments := make([]string, len(spec.segments))
	for i, value := range spec.segments {
		segments[i] = fmt.Sprintf("%q", value)
	}
	route := strings.Join(segments, ", ") + ", id"
	text := fmt.Sprintf(`// Code generated by sdkgen from Gophercloud v2.15.0 and the pinned Neutron proxy; DO NOT EDIT.
package %s

import (
    "context"
    "fmt"

    "github.com/JSYoo5B/go-openstacksdk/request"
    "github.com/JSYoo5B/go-openstacksdk/resource"
)

type DeleteOpts = request.NeutronDeleteOpts
type DeleteOption = request.NeutronDeleteOption

func WithDeleteOptions(value DeleteOpts) DeleteOption { return request.WithNeutronDeleteOptions(value) }
func WithDeleteRevision(value int64) DeleteOption { return request.WithNeutronDeleteRevision(value) }
func WithDeleteIgnoreMissing(value bool) DeleteOption { return request.WithNeutronDeleteIgnoreMissing(value) }

// DeleteWithOptions submits a conditional deletion. Missing resources are
// ignored by default; WithDeleteIgnoreMissing(false) selects strict handling.
// A zero revision is a real condition, and later options override earlier ones.
func (a *API) DeleteWithOptions(ctx context.Context, id string, options ...DeleteOption) error {
    if a == nil || a.client == nil {
        return request.Wrap("DeleteWithOptions", %q, fmt.Errorf("%%w: configured client is required", resource.ErrInvalidOption))
    }
    return request.Wrap("DeleteWithOptions", %q, request.DeleteNeutron(ctx, a.client, a.client.ServiceURL(%s), options...))
}
`, name, name, name, route)
	source, err := format.Source([]byte(text))
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(g.root, spec.path, "delete_options_generated.go"), source, 0644)
}
