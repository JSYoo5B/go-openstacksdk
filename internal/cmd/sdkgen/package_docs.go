package main

import (
	"errors"
	"fmt"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

const packageDocFile = "doc_generated.go"

func apiPackageDoc(upstreamPath, name string) string {
	sdk := strings.Split(sdkPath(upstreamPath), "/")
	upstream := strings.TrimPrefix(upstreamPath, upstreamModule+"/")
	text := fmt.Sprintf("Package %s exposes Gophercloud v2.15.0's %s calls through API, with concrete options, the SDK's request call categories and typed results.", name, upstream)
	if spec, ok := serviceSpecs[sdk[0]]; ok && len(sdk) > 2 {
		method := spec.name + strings.ToUpper(sdk[1][:1]) + sdk[1][1:]
		text += fmt.Sprintf(" Connection.%s returns the %s/%s service, whose %s field provides this API.", method, sdk[0], sdk[1], registryField(strings.Join(sdk[2:], "/")))
	}
	return text
}

func servicePackageDoc(key string, spec serviceSpec) string {
	parts := strings.Split(key, "/")
	method := spec.name + strings.ToUpper(parts[1][:1]) + parts[1][1:]
	return fmt.Sprintf("Package %s is the %s %s service. Connection.%s returns a Service whose fields expose the API packages below this directory; README.md gives an overview.", parts[1], spec.name, parts[1], method)
}

func writePackageDoc(dir, name, text string) error {
	path := filepath.Join(dir, packageDocFile)
	documented, err := hasHandwrittenPackageDoc(dir)
	if err != nil {
		return err
	}
	if documented {
		if err := os.Remove(path); err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
		return nil
	}
	var out strings.Builder
	out.WriteString("// Code generated by sdkgen; DO NOT EDIT.\n\n")
	for _, line := range wrapComment(text, 77) {
		out.WriteString("// " + line + "\n")
	}
	out.WriteString("package " + name + "\n")
	return os.WriteFile(path, []byte(out.String()), 0644)
}

func hasHandwrittenPackageDoc(dir string) (bool, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return false, err
	}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || strings.HasSuffix(name, "_generated.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(dir, name), nil, parser.PackageClauseOnly|parser.ParseComments)
		if err != nil {
			return false, err
		}
		if file.Doc != nil {
			return true, nil
		}
	}
	return false, nil
}

func wrapComment(text string, width int) []string {
	var lines []string
	line := ""
	for _, word := range strings.Fields(text) {
		if line != "" && len(line)+1+len(word) > width {
			lines = append(lines, line)
			line = word
			continue
		}
		if line != "" {
			line += " "
		}
		line += word
	}
	if line != "" {
		lines = append(lines, line)
	}
	return lines
}
